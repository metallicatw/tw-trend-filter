#: 快照裡每一個數字存到小數第幾位。
#:
#: ## 為什麼要有這張表（而不是全部 round(x, 2)）
#:
#: 快照存的是**拿去和門檻比大小**的數字，所以存進去的精度就是判定的精度。
#: 原本一律 round(…, 2)，於是桌機版和這裡會在邊界上給出不同的答案——實測：
#:
#:     量比原值 1.1951   桌機版 1.1951 < 1.2 → 淘汰
#:                       這裡   round(…,2)=1.2 → 1.2 < 1.2 為假 → 通過
#:
#:     20日均量 1000.4   桌機版 1000.4 <= 1000 為假 → 通過
#:                       這裡   round(…)=1000 → 1000 <= 1000 → 淘汰
#:
#: 兩個方向都會錯，所以不是「寬一點」或「嚴一點」，是**對不起來**。
#:
#: ## 為什麼不是「全部存全精度」就好
#:
#: 量過：1,900 檔全精度，gzip 之後這一份快照從 146 KB 變成 494 KB。那是使用者
#: 手機上真的要下載的東西，而這一段的目的只是讓邊界判定正確，不是把 float64
#: 的每一位都送到瀏覽器。
#:
#: 所以分兩種情形處理：
#:
#: * **和使用者設定的門檻比**（close/vol20/amt20/bw/vol_ratio）——門檻是從畫面
#:   上的數字框來的，最細也只到小數第二位。存到第六位，要翻轉就得有人把門檻
#:   打到小數第七位，那個輸入框打不出來。
#: * **兩個算出來的數字互比**（close vs ma60、ma20 vs ma60、close vs 布林上軌
#:   ／Donchian）——這種**沒有門檻可言**，兩邊可以任意接近，多存幾位都不保險。
#:   這幾個判定沒有任何一個規則參數在調它們，所以直接在 Python 這邊用完整的
#:   float64 算完，存成布林值（trend_ok / brk_boll / brk_don）。判定不再經過
#:   四捨五入，而 ma20/ma60/boll_up/donchian 就退回純顯示用，兩位小數綽綽有餘。
#:
#: 結果是：判定和桌機版逐位相同，而快照只大了幾十 KB（三個布林值壓縮得很好）。
SNAPSHOT_PRECISION: dict[str, int] = {
    'close': 6,        # ① 和 min_price 比
    'vol20': 2,        # ① 和 min_vol20 比（1000.4 那個例子）
    'amt20': 0,        # ① 和 min_amount 比：門檻 5,000 萬，1 元是它的 2e-8
    'ma20': 2,         # 只給畫面看
    'ma60': 2,         # 只給畫面看
    'boll_up': 2,      # 只給畫面看
    'donchian': 2,     # 只給畫面看
    'vol_ratio': 6,    # ④ 和 vol_ratio 比（1.1951 那個例子）
    'atr14': 2,        # 只給畫面看（停損價另外算）
    'six': 4,          # ∩ 和 min_six 比。六大是六個整數的平均，n/6 四位就夠
    'rr': 6,           # ∩ 和 min_rr 比。門檻來自數字框（step 0.1），六位保險
}


def _snap_round(key: str, value: float) -> float:
    """照 `SNAPSHOT_PRECISION` 存一個數字。

    寫成函式而不是在每一行寫 `round(x, 6)`，是因為「這一格存幾位」是一個要跟
    門檻對齊的決定，不是隨手選的常數——寫在同一張表裡才看得出它和門檻的關係。
    0 位就存整數，免得 JSON 裡多出一堆沒有意義的 `.0`。

    `KeyError` 是故意不接的：新增一個快照欄位卻忘了決定它要存幾位，應該當場
    壞掉，而不是安靜地沿用某個預設值。
    """
    digits = SNAPSHOT_PRECISION[key]
    return round(value) if digits == 0 else round(value, digits)


def snapshot_row(snap: dict) -> list:
    """把一檔的快照壓成一列，順序照 `SNAPSHOT_COLUMNS`。"""
    return [snap[k] for k in SNAPSHOT_COLUMNS]


def passes(snap: dict, rules: Rules) -> tuple[bool, list[str]]:
    """這一檔在這一組門檻下過不過，以及觸發了哪幾個訊號。

    ## 為什麼這個函式要存在

    四部曲的每一個可調門檻，最後都只是拿一個數字去比大小——所以「換一組門檻會
    篩出哪幾檔」不需要重算任何指標，只需要這一份快照。這個函式就是那份判定，
    而網頁上那一份 JS 是它的逐行翻譯：同一組輸入必須得到同一個答案。

    `tests/test_snapshot.py` 拿真的資料兩邊對過。兩份實作是刻意的重複——瀏覽器
    裡跑不了 Python，而唯一的替代方案是把判定搬去伺服器，那就回到「按一下等
    三十分鐘」。重複的代價由測試扛著。
    """
    if snap['close'] <= rules.min_price:
        return False, []
    if snap['vol20'] <= rules.min_vol20 or snap['amt20'] <= rules.min_amount:
        return False, []
    # ② 讀的是 `trend_ok`，不是自己拿 ma60 再比一次。
    #
    # 這一行以前是 `snap['close'] <= snap['ma60'] or snap['ma20'] <= snap['ma60']`，
    # 而快照裡那三個數字是四捨五入過的——close 和 ma60 差在小數第三位的時候，
    # 兩邊會被捨到同一個值，`<=` 於是成立，那一檔就被判成「沒站上季線」。
    # 桌機版拿的是完整的 float64，所以同一檔在那邊是通過的。
    #
    # ② 沒有任何門檻可調，所以這個答案在算指標的當下就定了。見 SNAPSHOT_PRECISION。
    if not snap['trend_ok']:
        return False, []

    # ③ 「過去 N 天內」——回看天數不能超過快照存了幾天。
    #
    # 下界那個 max(…, 0) 不是防呆：`bw[-look:]` 在 look 為負的時候**不會出錯**，
    # 它會安靜地換一個意思——`bw[-(-5):]` 是 `bw[5:]`，看的是最舊的那幾天。
    # 網頁上那個輸入框攔不住有人打負數，所以兩邊都先夾住。
    look = min(max(int(rules.lookback), 0), SNAPSHOT_DAYS)
    ago = snap['cross_ago']
    golden = 0 < ago <= look
    window = snap['bw'][-look:] if look else []
    squeeze = any(v <= rules.squeeze for v in window)
    if not (golden or squeeze):
        return False, []

    # ④ 的兩個突破同樣讀快照裡算好的布林值，理由和 ② 一樣：收盤價和布林上軌
    # ／Donchian 上緣可以差在小數第十位，而它們也沒有門檻可調。
    brk_boll, brk_don = snap['brk_boll'], snap['brk_don']
    if not (brk_boll or brk_don):
        return False, []
    if snap['vol_ratio'] < rules.vol_ratio:
        return False, []

    triggers = []
    if golden:
        triggers.append('黃金交叉')
    if squeeze:
        triggers.append('布林壓縮')
    if brk_boll:
        triggers.append('突破布林上軌')
    if brk_don:
        triggers.append('突破20日高點')
    return True, triggers


# ===============================================================
# 〔趨勢∩六大∩報酬〕：第五道關卡
# ===============================================================
#
# 四部曲講的是「今天技術面在動」。這一關問的是另一件事：**這家公司的體質與
# 價位值不值得**。兩者互不相干，所以它是另外一道關卡，不是把四部曲改掉——
# `passes()` 與 `tfPass()` 一行都沒有為它動過。


def reward_risk(target, downside, close):
    """報酬風險比，以及「沒有下檔風險」。回 `(rr, risk_free)`。

    ## 為什麼這一步在這裡算，不是由 tw-six-metrics 算好送過來

    報酬風險比拆開來是

        目標價 ＝ 歷年本益比高 × 預估EPS      ← 和今天的股價無關
        下檔價 ＝ 歷年本益比低 × 預估EPS      ← 和今天的股價無關
        報酬風險比 ＝ |(目標價/股價 − 1) ÷ (下檔價/股價 − 1)|

    只有最後一步要股價，而**這支程式手上就有今天的收盤**——它為了畫線圖把全
    市場的 OHLCV 都抓下來了。對面發前兩個、這邊算最後一步，兩邊用的就是同一
    天的同一個價格。

    由對面算好再送過來的話，這支程式得排在它後面才拿得到當天的值，而它目前跑
    在前面 34 分鐘（07:07 UTC vs 07:41 UTC）。要對齊就得整條排程往後推。

    而且同一天不只是好看：四部曲挑的是「今天突破、今天放量」的股票，也就是
    **今天剛漲上去**的那一批。用昨天的價格算，分母偏低、報酬被高估、報酬風險
    比系統性偏高——偏差的方向剛好倒向「看起來更該買」。那不是雜訊，是有方向的。

    ## 三種答案

        (rr, False)    一般情況。
        (None, True)   股價已經低於下檔價：**沒有下檔風險**，四段裡最好的那種。
        (None, False)  算不出來（對面沒有這一檔的目標價，多半是缺〔年度交易
                       資訊〕所以沒有本益比區間）。

    中間那個和最後一個都沒有數字，意思卻正好相反。拿 `>= 門檻` 去篩會把最好的
    那一批和沒資料的一起丟掉——而丟掉的方式是「它們不在名單上」，沒有徵兆。

    `0.0` 是第四種：股價已經高過目標價，沒有上檔可分。那是一個**算得出來的
    答案**（答案是不要買），不是缺資料。
    """
    if target is None or downside is None or not close or close <= 0:
        return None, False
    if close <= downside:
        return None, True
    ret = target / close - 1
    if ret <= 0:
        # `abs(ret / risk)` 在這裡會把兩個負號約掉，給出一個很漂亮的大數字。
        # tw-six-metrics 那邊實測有 4 檔這樣來的（南俊國際 582 倍配 −100% 的
        # 預期報酬）。四個判斷準則從頭到尾預設報酬是正的。
        return 0.0, False
    risk = downside / close - 1
    if not risk:
        return None, False
    return abs(ret / risk), False


def cross_passes(snap: dict, min_six: float, min_rr: float) -> bool:
    """六大評分與報酬風險比這一關過不過。

    網頁上那一份 `tfCross` 是這個函式的逐行翻譯，`tests/test_snapshot.py` 拿
    真的資料兩邊對過——和 `passes()`／`tfPass()` 同一個約定。

    門檻是 0 就等於這一關不啟用：〔台股趨勢選股〕那一頁的預設值是 0，
    〔趨勢∩六大∩報酬〕是 3 和 2。同一份報告、同一段程式，兩個入口。
    """
    if min_six > 0:
        six = snap.get('six')
        if six is None or six <= min_six:
            return False
    if min_rr > 0:
        if snap.get('rr_free'):
            return True          # 沒有下檔風險，比任何門檻都好
        rr = snap.get('rr')
        if rr is None or rr <= min_rr:
            return False
    return True


